-- ============================================================
-- 회귀 스위트의 기준 버전 기록
--
-- 병합 전 검증의 통과/실패 숫자는 절대값이 아니다 — **어느 버전의 동작을 기준으로
-- 굳힌 시나리오인가** 에 대한 상대값이다. 지금까지 그 기준 버전은 어디에도 남지 않아서,
-- 리뷰어는 "시나리오 12건 통과" 가 무엇에 비해 통과인지 알 수 없었다.
--
-- 프로세스·의사결정은 리뷰어가 시나리오를 다시 만들 때 기준 버전을 고를 수 있다
-- (이 요청이 갈라져 나온 버전 / 지금 운영 중인 버전). 고를 수 있게 하는 순간 고른 결과가
-- 화면에 남아야 하므로, 스위트에 그 버전을 적어 둔다.
--
-- 예전 스위트는 NULL 이다 — 기준을 모른다는 사실을 그대로 둔다(임의로 추측해 채우면
-- 화면이 틀린 기준을 사실처럼 말한다). 다시 만들면 그때 채워진다.
-- ============================================================

ALTER TABLE public.resource_eval_suites
    ADD COLUMN IF NOT EXISTS baseline_ref text NULL;

COMMENT ON COLUMN public.resource_eval_suites.baseline_ref IS
    '이 시나리오들이 기준으로 굳힌 버전(bpmn/dmn 은 v1.0 같은 버전, 스킬은 브랜치). NULL 이면 기록 없음(예전 스위트).';
